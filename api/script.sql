CREATE TABLE IF NOT EXISTS group_likes (
    id SERIAL PRIMARY KEY,
    user_id INTEGER NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,
    group_id INTEGER NOT NULL
        REFERENCES card_groups(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT unique_user_group_like
        UNIQUE (user_id, group_id)
);

CREATE INDEX IF NOT EXISTS idx_group_likes_group_id
    ON group_likes(group_id);


CREATE TABLE IF NOT EXISTS card_review_progress (
    id BIGSERIAL PRIMARY KEY,

    user_id INTEGER NOT NULL
        REFERENCES users(id) ON DELETE CASCADE,

    card_id INTEGER NOT NULL
        REFERENCES cards(id) ON DELETE CASCADE,

    repetitions INTEGER NOT NULL DEFAULT 0
        CHECK (repetitions >= 0),

    interval_days INTEGER NOT NULL DEFAULT 0
        CHECK (interval_days >= 0),

    ease_factor NUMERIC(4,2) NOT NULL DEFAULT 2.50
        CHECK (ease_factor >= 1.30),

    due_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    last_reviewed_at TIMESTAMPTZ,

    last_rating VARCHAR(10)
        CHECK (
            last_rating IS NULL
            OR last_rating IN ('again', 'hard', 'good', 'easy')
        ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT unique_user_card_review
        UNIQUE (user_id, card_id)
);

CREATE INDEX IF NOT EXISTS idx_card_review_due
    ON card_review_progress (user_id, due_at);

CREATE INDEX IF NOT EXISTS idx_card_review_card
    ON card_review_progress (card_id);

