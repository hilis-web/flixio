CREATE TABLE IF NOT EXISTS card_review_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    card_id INTEGER NOT NULL,
    rating VARCHAR(10) NOT NULL
        CHECK (rating IN ('again', 'hard', 'good', 'easy')),
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_card_review_logs_user_date
    ON card_review_logs (user_id, reviewed_at DESC);

CREATE INDEX IF NOT EXISTS idx_card_review_logs_user_card
    ON card_review_logs (user_id, card_id);


CREATE TABLE IF NOT EXISTS daily_learning_goals (
    user_id INTEGER PRIMARY KEY,
    target_reviews INTEGER NOT NULL DEFAULT 20
        CHECK (target_reviews BETWEEN 5 AND 200),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


CREATE TABLE IF NOT EXISTS study_reminders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  enabled BOOLEAN NOT NULL DEFAULT FALSE,
  reminder_time TIME NOT NULL DEFAULT '19:00',
  timezone TEXT NOT NULL DEFAULT 'Europe/Madrid',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_study_reminders_enabled
ON study_reminders(enabled)
WHERE enabled = TRUE;
